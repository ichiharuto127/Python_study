# ========================================
# 第8章: NumPy — 配列の作成・形状・属性
# ========================================
# 実行: pip install numpy

import numpy as np

# ===== 配列の作成 =====

# リストから作成(1次元配列)
a_1 = np.array([1, 2, 3, 4, 5])

# 2次元配列
a_2 = np.array(
    [[1, 2, 3],
     [4, 5, 6]]
    )

# 3次元配列(例: 2×2の画像データ)
a_3 = np.array(
    [[[0, 0, 0], [256, 256, 0]],
     [[0, 256, 256], [256, 0, 256]]]
    )

# 特殊な配列
print(np.zeros((3, 4)))        # →3×4のゼロ行列
print(np.ones((2, 3)))         # →2×3の要素がすべて1の行列
print(np.eye(3))               # →3×3の単位行列
print(np.arange(0, 10, 2))     # →[0, 2, 4, 6, 8] 0から10未満の偶数
print(np.linspace(0, 1, 5))    # →[0, 0.25, 0.5, 0.75, 1.0] 0から1以下の等間隔な5要素
print(np.random.rand(3, 3))    # →3×3の乱数行列（0〜1）
print(np.empty((4, 4)))        # →4×4の空の行列（初期化されていない値）

# ===== 配列の形状・属性 =====

print(a_1.shape)    # →(5,) 要素数が5の1次元配列
print(a_2.shape)    # →(2, 3) 2行3列の2次元配列
print(a_3.shape)    # →(2, 2, 3) 2ブロック2行3列の3次元配列
print(a_2.dtype)    # →int64 データ型
print(a_2.ndim)     # →2 次元
print(a_2.size)     # →6 要素数

# ===== 形状変換 =====

print(a_2.reshape(3, 2))   # (3, 2) に変形
print(a_2.flatten())        # 1次元に平坦化
print(a_2.T)                # 転置
