# ========================================
# 第8章: NumPy — 演算とブロードキャスト
# ========================================

import numpy as np

# ===== 要素ごとの演算 =====

a = np.array([1, 2, 3])
b = np.array([4, 5, 6])

print(a + b)      # [5, 7, 9]
print(a * b)      # [4, 10, 18]
print(a ** 2)     # [1, 4, 9]
print(a / b)      # [0.25, 0.4, 0.5]

# ===== ブロードキャスト（形状が異なる配列の演算）=====

# スカラーとのブロードキャスト
print(a + 10)     # [11, 12, 13]

# 形状が異なる配列同士
a = np.array([1, 2, 3])           # shape: (3,)
c = np.array([[1], [2], [3]])     # shape: (3, 1)

print(a + c)
# [[2, 3, 4],
#  [3, 4, 5],
#  [4, 5, 6]]

# ===== 行列積 =====

A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])

print(np.dot(A, B))
# [[19, 22],
#  [43, 50]]

# @ 演算子でも同じ
print(A @ B)
